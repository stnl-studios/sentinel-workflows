import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import test from 'node:test';
import { createOfflineCheckout } from './fixtures/offline-checkout.mjs';
const ROOT = path.resolve(import.meta.dirname, '..');
for (const boundary of ['private', 'published']) test(`APPLY replay after ${boundary} effects and failed finalization write`, { timeout: 90_000 }, async t => {
  const fixture = await createOfflineCheckout(t, ROOT, 'apply-replay-' + boundary);
  console.log(`TEST-ONLY replay fixture: ${fixture.root}`);
  const result = spawnSync(process.execPath, ['benchmarks/sentinel-todo/runtime/benchmark-manager.mjs', 'run', '--case', 'B'], { cwd: fixture.root, env: fixture.env, encoding: 'utf8', timeout: 75_000, maxBuffer: 4 * 1024 * 1024 });
  await fs.writeFile(path.join(fixture.root, '.offline-replay-manager.log'), result.stdout + '\n' + result.stderr);
  const observed = JSON.parse(await fs.readFile(path.join(fixture.root, `.offline-findings-replay-${boundary}.json`)));
  assert.equal(observed.first.exit, 1);
  assert.equal(observed.preparationStatus, 'PREPARED');
  assert.equal(observed.replay.exit, 0, observed.replay.diagnostic);
  assert.deepEqual(observed.afterReplay, observed.afterFault);
  assert.ok(observed.probes.length >= 7);
  assert.equal(result.status, 0, result.stderr);
  const calls = (await fs.readFile(path.join(fixture.root, '.offline-calls.jsonl'), 'utf8')).trim().split('\n').map(JSON.parse);
  assert.equal(calls.filter(call => call.independent && call.operation === 'APPLY_FINDINGS').length, 2, 'replay consumes no runner');
  assert.ok(calls.every(call => call.externalCalls === 0 && call.caseId === 'B'));
  const cycle = JSON.parse(await fs.readFile(path.join(fixture.root, '.offline-findings-cycle-observed.json')));
  assert.equal((cycle.publishedTask.match(/### findings-check-/gu) ?? []).length, 2, 'each receipt appears exactly once');
  assert.deepEqual(cycle.before, cycle.after);
  const firstRaw = JSON.parse(await fs.readFile(cycle.firstReceipt.semanticResponseFile));
  assert.ok(!('automaticCheckRound' in firstRaw) && !('findingsCycle' in firstRaw));
  assert.equal(cycle.firstReceipt.automaticCheckRound, '1/3');
});
