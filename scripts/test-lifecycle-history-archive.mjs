test('partial copy, fsync, and readback failures preserve every original and permit an independent safe retry',async t=>{
 const {target,roots}=await history(t,2),before=new Map();
 for(const name of await fs.readdir(roots.materialRoot)){const dir=path.join(roots.materialRoot,name);if(!(await fs.stat(dir)).isDirectory())continue;for(const leaf of await fs.readdir(dir))before.set(path.join(dir,leaf),await fs.readFile(path.join(dir,leaf)));}
 const open=fs.open;
 for(const fault of ['copy','file-fsync','parent-fsync','parent-unsupported','readback']){
  let fired=false,archiveOpened=false;
  fs.open=async function(file,...args){
   const isArchive=typeof file==='string'&&file.includes('.close-history-');
   if(isArchive&&archiveOpened&&fault==='readback'&&!fired){fired=true;throw Object.assign(new Error('controlled archive readback failure'),{code:'EIO'});}
   const handle=await open.call(this,file,...args);
   if(isArchive&&!archiveOpened){archiveOpened=true;
    if(fault==='copy'){const write=handle.writeFile.bind(handle);handle.writeFile=async bytes=>{await write(bytes.subarray(0,16));fired=true;throw Object.assign(new Error('controlled archive disk full'),{code:'ENOSPC'});};}
    if(fault==='file-fsync')handle.sync=async()=>{fired=true;throw Object.assign(new Error('controlled archive fsync failure'),{code:'EIO'});};
   }
   if(file===roots.leaseParent&&archiveOpened&&['parent-fsync','parent-unsupported'].includes(fault)&&!fired)handle.sync=async()=>{fired=true;throw Object.assign(new Error('controlled archive parent fsync failure'),{code:fault==='parent-unsupported'?'EOPNOTSUPP':'EIO'});};
   return handle;
  };syncBuiltinESMExports();
  try{await assert.rejects(publishCandidate('CLOSE',target,null),/controlled archive/u);}finally{fs.open=open;syncBuiltinESMExports();}
  assert.equal(fired,true,fault);for(const [file,bytes] of before)assert.deepEqual(await fs.readFile(file),bytes);
 }
 const result=await publishCandidate('CLOSE',target,null);assert.equal(result.cleanup,'complete');assert.ok(result.historicalArchive);
 const archives=(await fs.readdir(roots.leaseParent)).filter(name=>name.includes('.close-history-'));assert.equal(archives.length,6,'unbound partial files are retained, never adopted or silently deleted');
});

